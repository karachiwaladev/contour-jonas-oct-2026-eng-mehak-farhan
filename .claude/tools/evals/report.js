// Scoring and the markdown scorecard for a ticket eval.
const WEIGHT = { PASS: 1, WARN: 0.5, FAIL: 0 };
const ICON = { PASS: '✅', WARN: '⚠️', FAIL: '❌', SKIP: '➖' };

// Per-area score (0-100) over counted checks: PASS = 1, WARN = 0.5, FAIL = 0, SKIP not counted.
function summarize(checks) {
  const out = {};
  let total = 0, counted = 0;
  for (const area of [...new Set(checks.map((c) => c.area))]) {
    const scored = checks.filter((c) => c.area === area && c.status in WEIGHT);
    const pts = scored.reduce((n, c) => n + WEIGHT[c.status], 0);
    out[area] = { score: scored.length ? Math.round((100 * pts) / scored.length) : null, counted: scored.length };
    total += pts;
    counted += scored.length;
  }
  out.overall = counted ? Math.round((100 * total) / counted) : null;
  return out;
}

function renderMarkdown({ ticket, title, prs, checks, risk, base, head }) {
  const s = summarize(checks);
  const fmt = (v) => (v === null ? 'n/a' : `${v}/100`);
  const lines = [
    `## 📊 Ticket eval: #${ticket} ${title}`,
    '',
    `**Overall ${fmt(s.overall)}** · Engineering ${fmt(s.Engineering ? s.Engineering.score : null)} · QA ${fmt(s.QA ? s.QA.score : null)}` +
      (risk ? ` · Risk: **${risk.level}** (${risk.score}/100)` : ''),
    '',
    `PRs: ${prs.length ? prs.map((p) => `#${p.number}`).join(', ') : 'none found'}` + (base && head ? ` · code compared: \`${base.slice(0, 7)}\` → \`${head.slice(0, 7)}\`` : ''),
    '',
  ];
  for (const area of ['Engineering', 'QA']) {
    const rows = checks.filter((c) => c.area === area);
    if (!rows.length) continue;
    lines.push(`### ${area}`, '', '| Check | Result | Detail |', '|---|---|---|');
    for (const c of rows) lines.push(`| ${c.name} | ${ICON[c.status]} ${c.status} | ${String(c.detail).replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`);
    lines.push('');
  }
  if (risk && risk.reasons.length) lines.push('<details><summary>Risk score reasons</summary>', '', ...risk.reasons.map((r) => `- ${r}`), '', '</details>', '');
  lines.push('Scoring: ✅ = 1, ⚠️ = 0.5, ❌ = 0, ➖ not counted. Generated by `.claude/tools/evals/ticket-eval.js`.', '', '<!-- factory:eval -->');
  return lines.join('\n');
}

module.exports = { summarize, renderMarkdown };
