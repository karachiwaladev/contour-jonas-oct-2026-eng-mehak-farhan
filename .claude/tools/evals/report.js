// Scoring and the markdown scorecard for the coverage eval.
const WEIGHT = { PASS: 1, WARN: 0.5, FAIL: 0 };
const ICON = { PASS: '✅', WARN: '⚠️', FAIL: '❌', SKIP: '➖' };

// Score 0-100 over counted rows: PASS = 1, WARN = 0.5, FAIL = 0, SKIP not counted.
function summarize(rows) {
  const scored = rows.filter((r) => r.status in WEIGHT);
  const pts = scored.reduce((n, r) => n + WEIGHT[r.status], 0);
  return { score: scored.length ? Math.round((100 * pts) / scored.length) : null, counted: scored.length };
}

function renderMarkdown({ ticket, title, prs, rows, base, head, notes = [] }) {
  const { score } = summarize(rows);
  const lines = [
    `## 📊 Coverage eval: #${ticket} ${title}`,
    '',
    `**Score ${score === null ? 'n/a' : `${score}/100`}** · files the ticket changed must have ≥ 80% line coverage (target 90%)`,
    '',
    `PRs: ${prs.length ? prs.map((p) => `#${p.number}`).join(', ') : 'none found'}` + (base && head ? ` · code at \`${head.slice(0, 7)}\` (ticket changes since \`${base.slice(0, 7)}\`)` : ''),
    '',
    '| File | Result | Coverage |',
    '|---|---|---|',
    ...rows.map((r) => `| ${r.name} | ${ICON[r.status]} ${r.status} | ${String(r.detail).replace(/\|/g, '\\|')} |`),
    '',
    ...notes.map((n) => `- ${n}`),
    notes.length ? '' : null,
    'Scoring: ✅ ≥ 90% = 1, ⚠️ 80–90% = 0.5, ❌ < 80% = 0. Generated by `.claude/tools/evals/coverage-eval.js`.',
    '',
    '<!-- factory:eval -->',
  ].filter((l) => l !== null);
  return lines.join('\n');
}

module.exports = { summarize, renderMarkdown };
